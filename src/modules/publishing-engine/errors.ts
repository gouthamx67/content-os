/**
 * One error shape for every publishing failure.
 *
 * Validation findings are reported as data on the publication, not thrown, so
 * the codes here are the hard refusals: a missing row, a transition the state
 * machine forbids, a provider that is not configured, a provider that rejected
 * or lost a request, and a secret boundary that is not configured.
 */
export const PUBLISHING_ERROR_CODES = [
  "CONNECTION_NOT_FOUND",
  "PUBLICATION_NOT_FOUND",
  "RECOMMENDATION_NOT_FOUND",
  "PUBLISHING_INVALID_INPUT",
  "PUBLISHING_INVALID_TRANSITION",
  "PUBLICATION_NOT_VALIDATED",
  "PUBLICATION_VALIDATION_FAILED",
  "PUBLICATION_SCHEDULE_INVALID",
  "PUBLICATION_SCHEDULE_IN_PAST",
  "PUBLICATION_ALREADY_COMPLETED",
  "SOURCE_NOT_FOUND",
  "SOURCE_NOT_APPROVED",
  "SOURCE_GROUNDING_FAILED",
  "SOURCE_UNRESOLVED",
  "PUBLISHING_PROVIDER_UNAVAILABLE",
  "PUBLISHING_PROVIDER_AUTH",
  "PUBLISHING_PROVIDER_REJECTED",
  "PUBLISHING_PROVIDER_AMBIGUOUS",
  "PUBLISHING_PROVIDER_RATE_LIMITED",
  "PUBLISHING_NETWORK_ERROR",
  "PUBLISHING_SECRETS_UNAVAILABLE",
  "PUBLISHING_OAUTH_STATE_INVALID",
  "PUBLISHING_OAUTH_EXCHANGE_FAILED",
  "CONNECTION_NOT_CONNECTED",
  "CONNECTION_ALREADY_CONNECTED",
  "ANALYTICS_NOT_AVAILABLE",
  "ANALYTICS_INVALID_METRICS",
  "OPTIMIZATION_INSUFFICIENT_EVIDENCE",
  "OPTIMIZATION_ALREADY_REVIEWED",
  "OPTIMIZATION_NO_SOURCE",
] as const;
export type PublishingErrorCode = (typeof PUBLISHING_ERROR_CODES)[number];

const STATUS_BY_CODE: Record<PublishingErrorCode, number> = {
  CONNECTION_NOT_FOUND: 404,
  PUBLICATION_NOT_FOUND: 404,
  RECOMMENDATION_NOT_FOUND: 404,
  PUBLISHING_INVALID_INPUT: 400,
  PUBLISHING_INVALID_TRANSITION: 409,
  PUBLICATION_NOT_VALIDATED: 409,
  PUBLICATION_VALIDATION_FAILED: 422,
  PUBLICATION_SCHEDULE_INVALID: 400,
  PUBLICATION_SCHEDULE_IN_PAST: 400,
  PUBLICATION_ALREADY_COMPLETED: 409,
  SOURCE_NOT_FOUND: 404,
  SOURCE_NOT_APPROVED: 409,
  SOURCE_GROUNDING_FAILED: 422,
  SOURCE_UNRESOLVED: 409,
  PUBLISHING_PROVIDER_UNAVAILABLE: 503,
  PUBLISHING_PROVIDER_AUTH: 502,
  PUBLISHING_PROVIDER_REJECTED: 422,
  PUBLISHING_PROVIDER_AMBIGUOUS: 502,
  PUBLISHING_PROVIDER_RATE_LIMITED: 503,
  PUBLISHING_NETWORK_ERROR: 502,
  PUBLISHING_SECRETS_UNAVAILABLE: 503,
  PUBLISHING_OAUTH_STATE_INVALID: 400,
  PUBLISHING_OAUTH_EXCHANGE_FAILED: 502,
  CONNECTION_NOT_CONNECTED: 409,
  CONNECTION_ALREADY_CONNECTED: 409,
  ANALYTICS_NOT_AVAILABLE: 409,
  ANALYTICS_INVALID_METRICS: 502,
  OPTIMIZATION_INSUFFICIENT_EVIDENCE: 409,
  OPTIMIZATION_ALREADY_REVIEWED: 409,
  OPTIMIZATION_NO_SOURCE: 409,
};

export class PublishingError extends Error {
  readonly code: PublishingErrorCode;
  readonly status: number;
  readonly extras: Record<string, unknown>;

  constructor(
    code: PublishingErrorCode,
    message: string,
    extras: Record<string, unknown> = {},
  ) {
    super(message);
    this.name = "PublishingError";
    this.code = code;
    this.status = STATUS_BY_CODE[code];
    this.extras = extras;
  }
}

export function isPublishingError(error: unknown): error is PublishingError {
  return error instanceof PublishingError;
}
